function slugify(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
}

function buildParaphrasingSet(
  index: number,
  topicName: string,
  cards: Flashcard[],
  color: string,
  icon: string,
): FlashcardSet {
  const slug = slugify(topicName);
  return {
    id: `builtin:para-${String(index).padStart(2, "0")}-${slug}`,
    name: topicName,
    description: `${cards.length} thẻ từ vựng IELTS — đồng nghĩa, thành ngữ và ví dụ (chủ đề ${topicName}).`,
    icon,
    color,
    builtin: true,
    cards,
  };
}

