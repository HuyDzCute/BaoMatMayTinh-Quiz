function cleanText(s: string | undefined | null): string {
  if (!s) return "";
  return String(s)
    .replace(/\uFFFD+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

// Strip the "T\u1eef v\u1ef1ng v\u1ec1 " prefix common to every topic
// header so we can use the rest as a short, friendly name.
function topicShortName(name: string): string {
  return name.replace(/^T\u1eef\s+v\u1ef1ng\s+v\u1ec1\s+/i, "");
}

function buildOxfordSets(): FlashcardSet[] {
  const result: FlashcardSet[] = [];
  for (const t of SOURCE) {
    const short = topicShortName(t.name);
    const slug = slugify(short) || `topic-${t.index}`;
    const icon = TOPIC_ICONS[(t.index - 1) % TOPIC_ICONS.length];
    const color = TOPIC_COLORS[(t.index - 1) % TOPIC_COLORS.length];

    const cards: FlashcardSet["cards"] = t.cards.map((c, idx) => ({
      id: `oxford-${t.index}-${slug}-${idx + 1}`,
      front: cleanText(c.word),
      back: cleanText(c.meaning) || cleanText(c.word),
      pronunciation: cleanText(c.ipa) || undefined,
    }));

    result.push({
      id: `builtin:oxford-${String(t.index).padStart(2, "0")}-${slug}`,
      name: short,
      description: `${t.cards.length} t\u1eef v\u1ef1ng ti\u1ebfng Anh theo ch\u1ee7 \u0111\u1ec1 "${t.name}"`,
      icon,
      color,
      builtin: true,
      cards,
    });
  }
  return result;
}

export const builtinOxfordSets: FlashcardSet[] = buildOxfordSets();
