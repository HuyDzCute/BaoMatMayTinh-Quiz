// Cast once so the rest of this module is fully type-safe.
const SOURCE: SourceTopic[] = (oxfordData as { topics: SourceTopic[] }).topics;

/**
 * 3000 most common English vocabulary words, grouped by 60 everyday topics
 * (translated by Oxford Wordlist / popular Vietnamese learning resources).
 *
 * Source: `lib/oxford-3000-source.json` (generated by
 * `scripts/parse-oxford-source.cjs` from the supplied PDF).
 *
 * Each topic becomes its own FlashcardSet so the user can drill into one
 * area at a time. The set id is `builtin:oxford-{index}-{slug}` so users
 * can keep progress independently of the topic name.
 */
function slugify(input: string): string {
  return input
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
}

