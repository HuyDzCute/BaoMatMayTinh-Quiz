function restoreF(s) {
  if (!s) return s;
  // Replace tokens (Latin letters) only; skip Vietnamese.
  return s.replace(/[A-Za-z]+/g, (tok) => {
    if (tok.length < 3) return tok;
    // Single insertion at every position; if it produces a dict word, use it.
    for (let i = 1; i < tok.length; i++) {
      const v = tok.slice(0, i) + "f" + tok.slice(i);
      if (DICT.has(v.toLowerCase())) return v;
    }
    return tok;
  });
}

function fixFontFArtifacts(s) {
  if (!s) return s;
  return restoreF(s);
}

function main() {
  const raw = fs.readFileSync(SRC_PATH, "utf8");
  const lines = raw.split(/\r?\n/);

  const topics = [];
  let cur = null;
  let afterHeader = false;

  function flush() {
    if (cur) topics.push(cur);
    cur = null;
  }

  for (let rawLine of lines) {
    const line = rawLine.replace(/\s+$/g, "");
    const trimmed = line.trim();
    if (!trimmed) continue;

    // Topic header (e.g. "1. Từ vựng về đồ dùng học tập")
    const m = trimmed.match(TOPIC_RE);
    if (m && /Từ vựng về/i.test(trimmed)) {
      flush();
      cur = {
        index: parseInt(m[1], 10),
        name: m[2].trim(),
        cards: [],
      };
      afterHeader = false;
      continue;
    }

    if (!cur) continue;
    if (HEADER_RE.test(trimmed)) {
      afterHeader = true;
      continue;
    }

    if (line.includes("\t")) {
      const parts = line
        .split("\t")
        .map((s) => s.trim())
        .filter(Boolean);
      if (parts.length >= 3) {
        let word, pos, ipa, meaning;

        const posIdx = parts.findIndex((p) => POS_RE.test(p));
        if (posIdx >= 1 && posIdx + 1 < parts.length) {
          word = parts.slice(0, posIdx).join(" ");
          pos = parts[posIdx];
          ipa = parts[posIdx + 1].replace(/\s+/g, "");
          meaning = parts.slice(posIdx + 2).join(" ");
        } else {
          continue;
        }

        if (word && pos && ipa) {
          cur.cards.push({ word, pos, ipa, meaning: meaning || "" });
        }
        continue;
      }
    }

    if (!afterHeader) continue;
    const last = cur.cards[cur.cards.length - 1];
    if (!last) continue;
    if (POS_RE.test(trimmed)) continue;

    if (/^[/ˈˌɑɐɒɔəɛɪʊʌɜθðŋʃʒʧʤɲɳɴʎɹɻɺɫɬʔɡ]+/.test(trimmed) && /[/]/.test(trimmed)) {
      last.ipa = (last.ipa + trimmed.replace(/\s+/g, "")).trim();
    } else {
      last.meaning = (last.meaning + " " + trimmed).trim();
    }
  }
  flush();

  for (const t of topics) {
    for (const c of t.cards) {
      c.meaning = c.meaning.replace(/\s+\d{1,3}$/, "").trim();
      c.word = fixFontFArtifacts(c.word);
      c.meaning = fixFontFArtifacts(c.meaning);
      c.ipa = fixFontFArtifacts(c.ipa);
    }
  }

  const total = topics.reduce((a, t) => a + t.cards.length, 0);
  console.log(`Parsed ${topics.length} topics, ${total} cards.`);
  for (const t of topics) {
    console.log(`  ${String(t.index).padStart(2)}. ${t.name} (${t.cards.length} từ)`);
  }

  fs.writeFileSync(
    OUT_PATH,
    JSON.stringify(
      {
        source: "3000 từ vựng tiếng Anh thông dụng Oxford theo chủ đề",
        generatedAt: new Date().toISOString(),
        topics: topics.map((t) => ({
          index: t.index,
          name: t.name,
          cards: t.cards,
        })),
      },
      null,
      2,
    ),
    "utf8",
  );
  console.log(`Wrote: ${OUT_PATH}`);
}

main();
